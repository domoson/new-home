test('Szenenentwuerfe speichern, laden, umbenennen, exportieren und loeschen', async ({ page }, testInfo) => {
  test.setTimeout(240000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const openScene = async () => {
    await page.getByRole('button', { name: '3D', exact: true }).click()
    await page.locator('.scene-settings summary').click()
  }
  const stored = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), sceneDesignStorageKey)
  const selectDesign = page.getByLabel('Gespeicherter Entwurf', { exact: true })
  const designName = page.getByLabel('Entwurfsname', { exact: true })
  const save = page.getByRole('button', { name: 'Als neuen Entwurf speichern', exact: true })
  await page.goto('/')
  await openScene()
  await expect(page.getByLabel('Außenstil', { exact: true })).toHaveCount(0)
  await expect(selectDesign).toBeInViewport()
  await page.getByLabel('Fassadenentwurf', { exact: true }).selectOption('upper')
  await page.getByLabel('Holzprofil', { exact: true }).selectOption('grooved')
  await page.getByLabel('Oberfläche', { exact: true }).selectOption('oiled')
  await page.getByLabel('Holzart / Farbton', { exact: true }).selectOption('9')
  await page.getByLabel('Fensteranschluss', { exact: true }).selectOption('reveals')
  await page.getByLabel('Fassadenentwurf', { exact: true }).selectOption('custom')
  await expect(page.locator('#timber-area option')).toHaveCount(6)
  await page.getByRole('checkbox', { name: 'Holz Nord OG', exact: true }).uncheck()
  const lower = page.getByRole('slider', { name: 'Horizontal Beginn', exact: true })
  await lower.focus(); await lower.press('ArrowRight')
  await page.getByRole('button', { name: 'Putzausschnitt', exact: true }).click()
  await page.getByRole('button', { name: `Fenster innen ${finishes.frame[1].name}`, exact: true }).click()
  await page.getByRole('button', { name: 'Innentüren Eiche natur', exact: true }).click()
  await page.getByLabel('Haushälfte', { exact: true }).selectOption('west')
  await page.getByLabel('Fassadenentwurf', { exact: true }).selectOption('gable')
  await page.getByRole('button', { name: `Dach ${finishes.roof[0].name}`, exact: true }).click()
  await page.getByLabel('Eingangsüberdachung', { exact: true }).uncheck()
  await page.getByLabel('Datum', { exact: true }).selectOption('winter')
  await designName.fill('Holz und Zink')
  await save.click()
  const first = await stored(), firstId = first.lastSavedId
  expect(first.designs).toHaveLength(1)
  const snapshot = first.designs[0].settings
  expect(snapshot.timber.areas).toHaveLength(6)
  expect(snapshot.timber.areas.some(area => area.material === 'plaster')).toBe(true)
  expect(snapshot.timber.areas.some(area => area.from === .1)).toBe(true)
  expect(snapshot.west.entryCanopy).toBe(false)
  expect(snapshot.west.roof).toBe(finishes.roof[0].color)
  expect(snapshot.frameInside).toBe(finishes.frame[1].color)
  expect(snapshot.season).toBe('winter')
  await expect(page.locator('.scene-design-state')).toHaveText('Gespeichert · Startentwurf')
  await page.getByLabel('Datum', { exact: true }).selectOption('spring')
  await designName.fill('Fruehling')
  await save.click()
  const secondId = (await stored()).lastSavedId
  await selectDesign.selectOption(firstId)
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('winter')
  expect((await stored()).lastSavedId).toBe(secondId)
  await page.getByLabel('Datum', { exact: true }).selectOption('summer')
  page.once('dialog', dialog => dialog.dismiss())
  await selectDesign.selectOption(secondId)
  await expect(selectDesign).toHaveValue(firstId)
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('summer')
  await page.reload()
  await openScene()
  await expect(selectDesign).toHaveValue(secondId)
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('spring')
  await expect(page.getByLabel('Holzprofil', { exact: true })).toHaveValue('grooved')
  await expect(page.getByLabel('Oberfläche', { exact: true })).toHaveValue('oiled')
  await expect(page.locator('#timber-area option')).toHaveCount(6)
  await page.getByLabel('Haushälfte', { exact: true }).selectOption('west')
  await expect(page.getByLabel('Fassadenentwurf', { exact: true })).toHaveValue('gable')
  await expect(page.getByLabel('Eingangsüberdachung', { exact: true })).not.toBeChecked()
  await page.getByLabel('Haushälfte', { exact: true }).selectOption('east')
  await designName.fill('Mein Fruehlingsentwurf')
  await page.getByRole('button', { name: 'Entwurf umbenennen', exact: true }).click()
  expect((await stored()).designs[1].name).toBe('Mein Fruehlingsentwurf')
  await page.getByRole('button', { name: 'Entwürfe als JSON exportieren', exact: true }).click({ trial: true })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Entwürfe als JSON exportieren', exact: true }).click()
  const download = await downloadPromise
  const exported = await readFile((await download.path())!, 'utf8')
  expect(JSON.parse(exported)).toEqual(await stored())
  await page.getByLabel('Entwurfsdatei', { exact: true }).setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(exported) })
  await expect(selectDesign.locator('option')).toHaveCount(5)
  expect(new Set((await stored()).designs.map(design => design.id)).size).toBe(4)
  expect((await stored()).lastSavedId).toBe(secondId)
  const beforeInvalid = await stored()
  await page.getByLabel('Entwurfsdatei', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":999}') })
  await expect(page.getByRole('alert')).toContainText('Unbekanntes Entwurfsformat')
  expect(await stored()).toEqual(beforeInvalid)
  await designName.fill('Finaler Entwurf')
  await save.click()
  await save.hover()
  expect(await save.evaluate(button => ({ background: getComputedStyle(button).backgroundColor, color: getComputedStyle(button).color }))).toEqual({ background: 'rgb(54, 80, 62)', color: 'rgb(255, 255, 255)' })
  const finalId = (await stored()).lastSavedId
  await selectDesign.scrollIntoViewIfNeeded()
  expect(await page.locator('.settings-body').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('scene-design-controls.png') })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Entwurf löschen', exact: true }).click()
  expect((await stored()).designs.some(design => design.id === finalId)).toBe(false)
  expect((await stored()).lastSavedId).not.toBe(finalId)
  await page.locator('.scene-settings summary').click()
  await page.getByRole('button', { name: 'Dach', exact: true }).click()
  const image = PNG.sync.read(await page.locator('.scene-container canvas').screenshot({ path: testInfo.outputPath('scene-design-restored.png') }))
  const colors = new Set<string>()
  for (let offset = 0; offset < image.data.length; offset += 16) colors.add(`${image.data[offset]},${image.data[offset + 1]},${image.data[offset + 2]}`)
  expect(colors.size).toBeGreaterThan(100)
  const canvas = page.locator('.scene-container canvas'), bounds = (await canvas.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width * .4, bounds.y + bounds.height * .6)
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * .6, bounds.y + bounds.height * .6, { steps: 6 }); await page.mouse.up()
  const rotated = PNG.sync.read(await canvas.screenshot())
  expect(Buffer.compare(image.data, rotated.data)).not.toBe(0)
  expect(errors).toEqual([])
})

test('Beschaedigte oder gesperrte Speicherung laesst Entwurf und JSON-Sicherung intakt', async ({ page }) => {
  test.setTimeout(120000)
  await page.addInitScript(key => {
    if (!localStorage.getItem(key)) localStorage.setItem(key, '{corrupt')
    Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError') }
  }, sceneDesignStorageKey)
  await page.goto('/')
  await page.getByRole('button', { name: '3D', exact: true }).click()
  await page.locator('.scene-settings summary').click()
  await expect(page.getByRole('alert')).toContainText('nicht gelesen')
  await page.getByRole('button', { name: 'Als neuen Entwurf speichern', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Speichern im Browser fehlgeschlagen')
  expect(await page.evaluate(key => localStorage.getItem(key), sceneDesignStorageKey)).toBe('{corrupt')
  await expect(page.getByLabel('Gespeicherter Entwurf', { exact: true }).locator('option')).toHaveCount(1)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Entwürfe als JSON exportieren', exact: true }).click()
  const exported = JSON.parse(await readFile((await (await downloadPromise).path())!, 'utf8'))
  expect(exported.designs).toHaveLength(1)
  expect(exported.designs[0].settings.roof).toBe(initialSettings.roof)
  const valid = savedSnapshot(emptyDesignLibrary(), 'Import', initialSettings)
  await page.getByLabel('Entwurfsdatei', { exact: true }).setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(valid)) })
  await expect(page.getByRole('alert')).toContainText('Speichern im Browser fehlgeschlagen')
})